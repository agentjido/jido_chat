defmodule Jido.ChatAction.Execution do
  @moduledoc false
  alias Jido.Chat.Signal.{Identity, Policy, Schemas}

  @doc false
  def contract(action, definition, result_schema, env) do
    Code.ensure_compiled!(definition)

    {schema, capability} =
      case {Jido.Chat.Operations.Definitions.lookup(definition.type()), result_schema} do
        {{^definition, operation, _, _, schema}, nil} -> {schema, operation}
        {_, nil} -> raise ArgumentError, "Jido.ChatAction requires :result_schema for an extension Signal"
        {_, schema} -> {schema, nil}
      end

    operation = definition.type()
    completed = Module.concat(action, Completed)
    failed = Module.concat(action, Failed)
    define_result(completed, definition, "completed", completion_schema(operation, schema), env)
    define_result(failed, definition, "failed", failure_schema(operation), env)

    %{
      signal: definition,
      result_schema: schema,
      operation: operation,
      capability: capability,
      completed: completed,
      failed: failed
    }
  end

  defp define_result(module, request, suffix, schema, env) do
    Module.create(
      module,
      quote do
        @moduledoc "Typed chat Action result. Generated by Jido.ChatAction."
        use Jido.Chat.Signal.Definition,
          owner: :chat,
          kind: :result,
          type: unquote(request.type() <> "." <> suffix),
          dataschema: unquote(request.dataschema() <> ":" <> suffix),
          default_source: "urn:jido:chat:producer:local",
          schema: unquote(Macro.escape(schema))
      end,
      Macro.Env.location(env)
    )
  end

  defp completion_schema(operation, result) do
    Schemas.object(%{
      "client_id" => Schemas.id(),
      "request_id" => Schemas.id(),
      "operation" => Zoi.literal(operation),
      "result" => result
    })
  end

  defp failure_schema(operation) do
    Schemas.object(%{
      "client_id" => Schemas.id(),
      "request_id" => Schemas.id(),
      "operation" => Zoi.literal(operation),
      "code" =>
        Zoi.enum([
          "unsupported",
          "provider_failure",
          "invalid_provider_result",
          "unauthorized",
          "forbidden",
          "not_found",
          "rate_limited",
          "timeout"
        ]),
      "retry_after_ms" => Zoi.integer() |> Zoi.min(0) |> Zoi.optional(),
      "outcome" => Zoi.enum(["not_attempted", "rejected", "unknown"])
    })
  end

  @doc false
  def json_schema(definition) do
    fields = Map.new(Jido.Signal.schema().fields)
    envelope = Zoi.to_json_schema(Zoi.object(fields)) |> Jason.encode!() |> Jason.decode!()
    properties = envelope["properties"] |> Map.drop(["extensions", "data_present?", "data_base64?"])

    properties =
      Map.merge(properties, %{
        "type" => %{"const" => definition.type()},
        "dataschema" => %{"const" => definition.dataschema()},
        "data" => definition.schema() |> Zoi.to_json_schema() |> Jason.encode!() |> Jason.decode!(),
        "traceparent" => %{"type" => "string"},
        "tracestate" => %{"type" => "string"},
        "causationid" => %{"type" => "string"}
      })

    %{
      "type" => "object",
      "additionalProperties" => false,
      "required" => ["signal"],
      "properties" => %{
        "signal" => %{
          "type" => "object",
          "additionalProperties" => false,
          "required" => ["id", "source", "type", "dataschema", "data"],
          "properties" => properties
        }
      }
    }
  end

  @doc false
  def prepare_params(%{"signal" => signal} = params, definition) when map_size(params) == 1,
    do: prepare_params(%{signal: signal}, definition)

  def prepare_params(%{signal: signal} = params, definition) when is_map(signal) and not is_struct(signal) do
    with {:ok, native} <- Jido.Signal.Catalog.decode(Jido.Signal.Catalog.new!([definition]), signal),
         {:ok, native} <- checked_signal(native, definition) do
      {:ok, %{params | signal: native}}
    else
      _ -> Policy.error(:invalid_request)
    end
  end

  def prepare_params(params, _definition), do: {:ok, params}

  @doc false
  def timeout(action, client, request) do
    contract = %{failed: Module.concat(action, Failed), operation: action.signal_definition().type()}
    failure(contract, client, request, :timeout, "unknown")
  end

  @doc false
  def input_schema(definition) do
    field = Zoi.any(description: "Native Jido.Signal validated by its exact chat definition")
    field = Zoi.refine(field, {__MODULE__, :validate_signal, [definition]})
    Zoi.object(%{signal: field}, unrecognized_keys: :error)
  end

  @doc false
  def output_schema(contract) do
    field = Zoi.any(description: "Native Jido.Signal completion for this chat Action")
    field = Zoi.refine(field, {__MODULE__, :validate_completion, [contract.completed, contract.operation]})
    Zoi.object(%{signal: field}, unrecognized_keys: :error)
  end

  @doc false
  def validate_completion(signal, definition, operation, opts) do
    with :ok <- validate_signal(signal, definition, opts),
         true <- signal.data["operation"] == operation do
      :ok
    else
      _ -> {:error, "expected a completion for #{operation}"}
    end
  end

  @doc false
  def validate_signal(signal, definition, _opts) do
    case checked_signal(signal, definition) do
      {:ok, _} -> :ok
      _ -> {:error, "expected a valid #{definition.type()} Signal"}
    end
  end

  defp checked_signal(%Jido.Signal{} = signal, definition) do
    with true <- signal.type == definition.type() and signal.dataschema == definition.dataschema(),
         {:ok, signal} <- Jido.Signal.Catalog.validate(Jido.Signal.Catalog.new!([definition]), signal),
         :ok <- Policy.validate_json(signal.data, []),
         {:ok, signal} <- Policy.validate(signal) do
      {:ok, signal}
    else
      {:error, _} = error -> error
      _ -> Policy.error(:invalid_request)
    end
  end

  defp checked_signal(_, _), do: Policy.error(:invalid_request)

  @doc false
  def run(action, contract, %{signal: request}, %{client: %Jido.Chat.Client{} = client} = context) do
    opts = Map.get(context, :options, [])

    with {:ok, request} <- checked_signal(request, contract.signal),
         :ok <- validate_context(client, request),
         true <- is_list(opts) and Keyword.keyword?(opts) do
      if is_nil(contract.capability) or client.adapter.capabilities()[contract.capability] == :native do
        invoke(action, contract, client, request, opts)
      else
        failure(contract, client, request, :unsupported, "not_attempted")
      end
    else
      {:error, _} = error -> error
      _ -> Policy.error(:invalid_options)
    end
  end

  def run(_, _, _, _), do: Policy.error(:invalid_client)

  defp validate_context(client, request) do
    data = request.data

    valid =
      is_map(data) and is_binary(data["request_id"]) and data["request_id"] != "" and
        data["client_id"] == client.id and
        (not Map.has_key?(data, "room_id") or (is_binary(data["room_id"]) and data["room_id"] != ""))

    if valid and request.subject in [nil, subject(client, request)] and references_match?(data, client.id),
      do: :ok,
      else: Policy.error(:context_mismatch)
  end

  defp references_match?(value, client_id) when is_map(value) do
    matches =
      case value do
        %{"client_id" => ref_client, "id" => _, "kind" => kind} when kind in ["file", "media", "url"] ->
          ref_client == client_id

        _ ->
          true
      end

    matches and Enum.all?(value, fn {_, item} -> references_match?(item, client_id) end)
  end

  defp references_match?(value, client_id) when is_list(value),
    do: Enum.all?(value, &references_match?(&1, client_id))

  defp references_match?(_, _), do: true

  defp invoke(action, contract, client, request, opts) do
    case provider_call(action, client, request, opts) do
      {:ok, value} ->
        complete(contract, client, request, value)

      {:error, :invalid_provider_result} ->
        failure(contract, client, request, :invalid_provider_result, "unknown")

      {:error, {:unknown, code, hints}} when is_map(hints) ->
        failure(contract, client, request, safe_code(code), "unknown", hints)

      {:error, {:rejected, code, hints}} when is_map(hints) ->
        failure(contract, client, request, safe_code(code), "rejected", hints)

      {:error, {:rejected, code}} ->
        failure(contract, client, request, safe_code(code), "rejected")

      {:error, {:not_attempted, :unsupported}} ->
        failure(contract, client, request, :unsupported, "not_attempted")

      {:error, {:not_attempted, _}} ->
        failure(contract, client, request, :provider_failure, "not_attempted")

      _ ->
        failure(contract, client, request, :provider_failure, "unknown")
    end
  end

  defp complete(contract, client, request, value) do
    with {:ok, result} when is_map(result) <- Zoi.parse(contract.result_schema, value),
         :ok <- Policy.validate_json(result, []),
         true <- references_match?(result, client.id),
         true <-
           is_nil(request.data["room_id"]) or is_nil(result["room_id"]) or
             request.data["room_id"] == result["room_id"],
         {:ok, signal} <-
           contract.completed.new(
             result_data(contract, client, request) |> Map.put("result", result),
             result_options(client, request)
           ) do
      {:ok, %{signal: signal}}
    else
      _ -> failure(contract, client, request, :invalid_provider_result, "unknown")
    end
  end

  defp provider_call(action, client, request, opts) do
    action.invoke(client, request, opts)
  rescue
    _ -> {:error, :provider_failure}
  catch
    _, _ -> {:error, :provider_failure}
  end

  defp safe_code(code)
       when code in [
              :unsupported,
              :invalid_provider_result,
              :unauthorized,
              :forbidden,
              :not_found,
              :rate_limited,
              :timeout
            ],
       do: code

  defp safe_code(_), do: :provider_failure

  defp failure(contract, client, request, code, outcome, hints \\ %{}) do
    data = result_data(contract, client, request) |> Map.merge(%{"code" => Atom.to_string(code), "outcome" => outcome})

    data =
      case hints[:retry_after_ms] do
        value when is_integer(value) and value >= 0 -> Map.put(data, "retry_after_ms", value)
        _ -> data
      end

    with {:ok, signal} <- contract.failed.new(data, result_options(client, request)) do
      {:error, Jido.Chat.Error.exception(code: code, signal: signal)}
    end
  end

  defp result_data(contract, client, request),
    do: %{"client_id" => client.id, "request_id" => request.data["request_id"], "operation" => contract.operation}

  defp subject(client, request) do
    if request.data["room_id"], do: Identity.conversation_subject(client.id, request.data["room_id"])
  end

  defp result_options(client, request) do
    extensions = request.extensions |> Map.take(["traceparent", "tracestate"]) |> Map.put("causationid", request.id)
    [source: client.source, subject: subject(client, request), extensions: extensions]
  end
end
